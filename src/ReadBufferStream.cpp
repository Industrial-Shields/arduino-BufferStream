#include "ReadBufferStream.h"

////////////////////////////////////////////////////////////////////////////////////////////////////
ReadBufferStream::ReadBufferStream(const void *buff, size_t len) : BaseBufferStream((void*) buff, len) {
}

////////////////////////////////////////////////////////////////////////////////////////////////////
int ReadBufferStream::available() {
	return _len;
}

////////////////////////////////////////////////////////////////////////////////////////////////////
int ReadBufferStream::read() {
	if (_len == 0) {
		return -1;
	}
	--_len;
	return *_buff++;
}

////////////////////////////////////////////////////////////////////////////////////////////////////
int ReadBufferStream::peek() {
	if (_len == 0) {
		return -1;
	}
	return *_buff;
}
