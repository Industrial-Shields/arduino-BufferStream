#include "WriteBufferStream.h"

////////////////////////////////////////////////////////////////////////////////////////////////////
WriteBufferStream::WriteBufferStream(void *buff, size_t len) : BaseBufferStream(buff, len) {
}

////////////////////////////////////////////////////////////////////////////////////////////////////
size_t WriteBufferStream::write(uint8_t value) {
	if (_len == 0) {
		return 0;
	}
	*_buff++ = value;
	--_len;
	return 1;
}
